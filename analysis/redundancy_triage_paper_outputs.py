#!/usr/bin/env python3
"""Paper figure and table for the redundancy (omega_k = t * rho_e,k) on the prospective holdout,
MSE gains. Reads the outputs of analysis/redundancy_triage.py from --dir (paper version: the full
pre-registered holdout of job 101294, 243 configurations, --dir analysis/out_redundancy_triage_holdout1).

Writes, for k = 3 and 5: study_redundancy_single_seed_early_stop_K20_k{k}.pdf/.png (same design as the
paper's figure) and table_study_redundancy_early_stop.tex (rows k = 3 and 5, targets G_20 and G_200).
"""
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

D = "analysis/out_redundancy_triage_216"   # overridden by --dir
OUT = os.path.join(D, "paper")
COLORS = {7: "#86b6ef", 8: "#2a78d6", 10: "#104281"}       # ordinal blue, validated (dataviz skill)
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#6b6b68", "#e6e5e1", "#ffffff"


def figure(p, k):
    x = p[(p.statistic == "redundancy") & (p.k == k)]
    fig, ax = plt.subplots(figsize=(3.6, 3.2), facecolor=SURFACE)
    w, pos = 0.26, np.arange(3)
    for j, thr in enumerate((7, 8, 10)):
        g = x[x.threshold == thr].set_index("tertile").loc[["low", "mid", "high"]]
        ax.bar(pos + (j - 1) * w, 100 * g.p, width=w - 0.02, color=COLORS[thr],
               yerr=100 * g.se, error_kw=dict(ecolor=INK, lw=0.9, capsize=2.5),
               label=f"$G^{{test}}_{{20}} \\geq {thr}$")
    ax.set_xticks(pos, ["Low", "Middle", "High"])
    ax.set_xlabel(f"Redundancy tertile after {k} splits", color=INK)
    ax.set_ylabel("Probability", color=INK)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(decimals=0))
    ax.set_ylim(0, max(5, 100 * (x.p + x.se).max() * 1.15))
    ax.legend(title="Large sample gain\nif pushing to 20 splits", frameon=False, fontsize=7, title_fontsize=7.5,
              loc="upper right", labelcolor=INK)
    ax.grid(axis="y", color=GRID, lw=0.6); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelsize=8)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(OUT, f"study_redundancy_single_seed_early_stop_K20_k{k}.{ext}"), dpi=200, facecolor=SURFACE)
    plt.close(fig)


def table(t):
    x = t[t.statistic == "redundancy"]
    lines = [r"\begin{tabular}{@{}ccccccl@{}}", r"    \toprule",
             r"    \thead{Splits\\used} & \thead{Target} & \thead{Valid\\runs} & \thead{Corr. with\\log gain} & "
             r"\thead{Rank\\corr.} & \thead{Median gain\\low/mid/high red.} & \thead{Large-gain probability\\low/mid/high red.} \\",
             r"    \midrule"]
    for i, k in enumerate((3, 5)):
        for tgt, lab, thr in (("G_paper_20", r"$G^{\text{test}}_{20}$", 10), ("G_paper_200", r"$G^{\text{test}}_{200}$", 20)):
            r = x[(x.k == k) & (x.target == tgt)].iloc[0]
            med = "/".join(f"{r[f'median_gain_{q}']:.1f}" for q in ("low", "mid", "high"))
            pr = "/".join(f"{100 * r[f'P_large_{q}']:.1f}" for q in ("low", "mid", "high"))
            lines.append(f"    {k} & {lab} & {int(r.valid_runs):,} & ${r.log_corr:+.2f}$ & ${r.rank_corr:+.2f}$ & ${med}$ & "
                         f"$\\Pr({lab.strip('$')}\\ge{thr})={pr}\\%$ \\\\".replace(",", "{,}"))
        if i == 0:
            lines.append(r"    \midrule")
    lines += [r"    \bottomrule", r"\end{tabular}"]
    with open(os.path.join(OUT, "table_study_redundancy_early_stop.tex"), "w") as f:
        f.write("% Generated by analysis/redundancy_triage_paper_outputs.py: redundancy omega_k = t * rho_e,k,\n"
                f"% MSE gains (order-averaged), prospective holdout ({D}).\n"
                "% Requires \\usepackage{booktabs,makecell} (\\thead) as in the paper.\n" + "\n".join(lines) + "\n")


def main():
    import argparse
    global D, OUT
    ap = argparse.ArgumentParser(); ap.add_argument("--dir", default=D); a = ap.parse_args()
    D, OUT = a.dir, os.path.join(a.dir, "paper")
    os.makedirs(OUT, exist_ok=True)
    p = pd.read_csv(os.path.join(D, "probabilities_out_holdout_mse.csv"))
    t = pd.read_csv(os.path.join(D, "table_out_holdout_mse.csv"))
    for k in (3, 5):
        figure(p, k)
    table(t)
    print("wrote", sorted(os.listdir(OUT)))
    print(p[(p.statistic == "redundancy") & p.k.isin([3, 5])].round(4).to_string(index=False))


if __name__ == "__main__":
    main()
